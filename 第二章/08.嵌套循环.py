# 嵌套循环1与里面的循环2,当循环1开始,执行到循环2,必须要2走完,才能继续循环1
# 现在要求按客户要求生成一个长度为m,宽为n的长方形,长和宽用*代替
# 嵌套循环实例
# 1 先输入长和宽
m, n = map(int,input("请输入你想要制作的长方形的长和宽(用空格隔开): ").split())
# 2 接下来制造长方形,长为横的,宽为竖的,从上到下一行一行来
for i in range(n):# 控制行
    for j in range(m):# 这前面没有print输出啊,所以导致后面没有的话就自动堆到一行里面了
        print("*",end=" ")# print 语句自带换行效果,每一次输出都会输出到新的一行中
    #     end"" 表示这个print语句以什么结束,默认都是end"\n"(换行),这样子加了之后就不会换行了
    print()#最后的print默认换行操作,课件里讲的

