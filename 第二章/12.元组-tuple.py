# 元组一旦定义完成,无法进行修改,只能查询
# 元组是不可变的序列
# 列表不同的点,就是列表可以修改

# 方法count():统计元素在元组中出现的次数
# index():查找某个元素在元组中的索引位置(第一次出现的位置)
# tuple(元组)
# 可以切片
# 如果要定义单元素的元组,后面需要加,,(100,)

# 组包操作
t1 = (5, 7, 9, 10, 2, 23, 12)
t2 = 5, 7, 9, 10, 2, 23, 12
# 基础解包操作
a, b, c, d, e, f, g = t1
print(a, b, c, d, e, f, g)
# 进阶解包操作记得加*, *可以用来收集剩余的所有元素并且进行封装
n1, *n2, n3 =t2
print(n1, n2, n3)
